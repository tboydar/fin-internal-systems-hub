function retryFor(spec: Spec): Iface['retry'] {
  if (spec.via === 'esb') return RETRY_ESB;
  if (spec.via === 'file') return RETRY_FILE;
  if (spec.protocol === 'JDBC') return RETRY_JOB;
  // 直連的帳號同步會被對方限流，所以也要重試；單一登入失敗就請使用者重新登入
  return spec.schedule.kind === 'interval' ? RETRY_SYNC : RETRY_NONE;
}

export function buildIfaces(): Iface[] {
  return SPECS.map((s) => ({
    id: s.id,
    name: s.name,
    plain: s.plain,
    source: s.flow[0],
    target: s.flow[1],
    systemId: s.own[0],
    vendorId: s.own[1],
    ownerId: s.own[2],
    domain: s.domain,
    via: s.via,
    protocol: s.protocol,
    schedule: s.schedule,
    contract: s.contract,
    volume: s.volume,
    fields: s.fields,
    retry: retryFor(s),
    // 經整合層或走檔案的介面，重試用完會進 DLQ；直連的沒有 DLQ，失敗就整批重跑
    dlq: s.via !== 'direct',
    compensation: s.compensation,
    reconIds: s.reconIds ?? [],
    dependsOn: s.dependsOn ?? [],
    apiId: s.apiId,
    runbookId: s.runbookId,
    flaky: s.flaky,
  }));
}

